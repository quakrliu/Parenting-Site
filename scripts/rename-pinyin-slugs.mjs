/**
 * One-shot migration: rename 6 pinyin-slug guide files to SEO-friendly
 * English slugs, update frontmatter, rewrite internal links across all
 * blog posts, and emit public/_redirects with 301 rules.
 *
 * Idempotent — running again is a no-op once renames are done.
 *
 * Usage: node scripts/rename-pinyin-slugs.mjs
 */

import { readFileSync, writeFileSync, readdirSync, renameSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const GUIDES_DIR = join(ROOT, 'src', 'content', 'guides');
const BLOG_DIR = join(ROOT, 'src', 'content', 'blog');
const REDIRECTS_PATH = join(ROOT, 'public', '_redirects');

const MAPPING = {
  'chan-pin-ping-ce-zhinan':       'baby-product-guide-zh',
  'fa-zhan-li-cheng-bei-zhinan':   'child-milestones-guide-zh',
  'ju-jia-huan-jing-she-ji':       'montessori-home-environment-zh',
  'montessori-ju-jia-zhinan':      'montessori-home-complete-zh',
  'ying-er-ying-yang-jian-kang':   'baby-nutrition-feeding-zh',
  'zheng-xiang-jiao-yang-zhinan':  'positive-parenting-pillar-zh',
};

let renamedCount = 0;
let linkFileCount = 0;

// 1. Rename guide files + update frontmatter slug
for (const [oldSlug, newSlug] of Object.entries(MAPPING)) {
  const oldPath = join(GUIDES_DIR, `${oldSlug}.md`);
  const newPath = join(GUIDES_DIR, `${newSlug}.md`);

  if (existsSync(oldPath)) {
    let content = readFileSync(oldPath, 'utf8');
    content = content.replace(`slug: ${oldSlug}`, `slug: ${newSlug}`);
    writeFileSync(oldPath, content);
    renameSync(oldPath, newPath);
    console.log(`  rename  ${oldSlug}  →  ${newSlug}`);
    renamedCount++;
  } else if (existsSync(newPath)) {
    console.log(`  skip    ${newSlug} (already renamed)`);
  } else {
    console.log(`  ✗ missing  ${oldSlug}.md`);
  }
}

// 2. Rewrite internal links across all blog .md files
const blogFiles = readdirSync(BLOG_DIR).filter((f) => f.endsWith('.md'));
for (const f of blogFiles) {
  const p = join(BLOG_DIR, f);
  let content = readFileSync(p, 'utf8');
  let changed = false;
  for (const [oldSlug, newSlug] of Object.entries(MAPPING)) {
    if (content.includes(oldSlug)) {
      content = content.split(oldSlug).join(newSlug);
      changed = true;
    }
  }
  if (changed) {
    writeFileSync(p, content);
    console.log(`  links   updated in  blog/${f}`);
    linkFileCount++;
  }
}

// 3. Emit / overwrite public/_redirects with 301 rules.
// Cover both trailing-slash variants for safety.
const lines = [
  '# 301 redirects from old pinyin slugs to SEO-friendly English slugs.',
  '# Generated by scripts/rename-pinyin-slugs.mjs',
  '',
];
for (const [oldSlug, newSlug] of Object.entries(MAPPING)) {
  for (const lang of ['zh', 'en']) {
    lines.push(`/${lang}/guides/${oldSlug}  /${lang}/guides/${newSlug}  301`);
    lines.push(`/${lang}/guides/${oldSlug}/ /${lang}/guides/${newSlug}/ 301`);
  }
}
writeFileSync(REDIRECTS_PATH, lines.join('\n') + '\n');
console.log(`\n  wrote   public/_redirects (${Object.keys(MAPPING).length * 4} rules)`);

console.log(`\nDone. Renamed ${renamedCount} guides, updated links in ${linkFileCount} blog posts.`);
